import '../../models/budget.dart';
import '../../models/recurring_transaction.dart';
import '../../models/transaction.dart';

/// Projected end-of-month spend for a single category/budget.
class BudgetForecast {
  final Budget budget;
  final double spentSoFar;

  /// Recurring expenses for this category still due before month end.
  final double remainingRecurring;

  /// Projected discretionary (non-recurring) spend for the rest of the month.
  final double projectedDiscretionary;

  /// spentSoFar + remainingRecurring + projectedDiscretionary.
  final double projectedTotal;

  const BudgetForecast({
    required this.budget,
    required this.spentSoFar,
    required this.remainingRecurring,
    required this.projectedDiscretionary,
    required this.projectedTotal,
  });

  bool get projectedToExceed => projectedTotal > budget.amount;
  double get projectedOverBy =>
      projectedToExceed ? projectedTotal - budget.amount : 0;
}

/// Projected totals for the whole current month.
class MonthForecast {
  final double incomeSoFar;
  final double expensesSoFar;
  final double projectedIncome;
  final double projectedExpenses;

  const MonthForecast({
    required this.incomeSoFar,
    required this.expensesSoFar,
    required this.projectedIncome,
    required this.projectedExpenses,
  });

  double get projectedNet => projectedIncome - projectedExpenses;
}

/// Offline month-end forecasting: actual month-to-date + remaining known
/// recurring occurrences + run-rate on the discretionary remainder.
///
/// Pure/stateless; the current date is injectable for testing.
class ForecastEngine {
  /// Projects end-of-month spend for [budget].
  ///
  /// [monthTransactions] are this month's transactions; [recurring] are the
  /// active recurring rules. Discretionary run-rate uses only the NON-recurring
  /// portion of month-to-date spend so fixed costs aren't double-counted or
  /// smeared.
  static BudgetForecast forecastBudget({
    required Budget budget,
    required List<Transaction> monthTransactions,
    required List<RecurringTransaction> recurring,
    DateTime? now,
  }) {
    final today = _dateOnly(now ?? DateTime.now());
    final monthEnd = DateTime(today.year, today.month + 1, 0);
    final daysInMonth = monthEnd.day;
    final daysElapsed = today.day;

    final catTx = monthTransactions.where((t) =>
        t.type == 'expense' && t.categoryId == budget.categoryId);

    final spentSoFar = catTx.fold(0.0, (s, t) => s + t.amount);
    // Portion of spend that was NOT generated by a recurring rule.
    final discretionarySoFar = catTx
        .where((t) => t.recurringId == null)
        .fold(0.0, (s, t) => s + t.amount);

    // Remaining recurring expense occurrences for this category this month.
    final remainingRecurring = _remainingRecurringForCategory(
      recurring: recurring,
      categoryId: budget.categoryId,
      from: today,
      monthEnd: monthEnd,
    );

    // Run-rate on discretionary spend across the rest of the month.
    final daysRemaining = daysInMonth - daysElapsed;
    final dailyDiscretionary =
        daysElapsed > 0 ? discretionarySoFar / daysElapsed : 0.0;
    final projectedDiscretionary = dailyDiscretionary * daysRemaining;

    final projectedTotal =
        spentSoFar + remainingRecurring + projectedDiscretionary;

    return BudgetForecast(
      budget: budget,
      spentSoFar: spentSoFar,
      remainingRecurring: remainingRecurring,
      projectedDiscretionary: projectedDiscretionary,
      projectedTotal: projectedTotal,
    );
  }

  /// Projects whole-month income and expense totals.
  static MonthForecast forecastMonth({
    required List<Transaction> monthTransactions,
    required List<RecurringTransaction> recurring,
    DateTime? now,
  }) {
    final today = _dateOnly(now ?? DateTime.now());
    final monthEnd = DateTime(today.year, today.month + 1, 0);
    final daysInMonth = monthEnd.day;
    final daysElapsed = today.day;
    final daysRemaining = daysInMonth - daysElapsed;

    double soFar(String type, {bool recurringOnly = false, bool discretionary = false}) {
      return monthTransactions
          .where((t) =>
              t.type == type &&
              (!discretionary || t.recurringId == null) &&
              (!recurringOnly || t.recurringId != null))
          .fold(0.0, (s, t) => s + t.amount);
    }

    final incomeSoFar = soFar('income');
    final expensesSoFar = soFar('expense');

    final incomeDiscretionary = soFar('income', discretionary: true);
    final expenseDiscretionary = soFar('expense', discretionary: true);

    final remainingRecurringIncome = _remainingRecurring(
        recurring, 'income', today, monthEnd);
    final remainingRecurringExpense = _remainingRecurring(
        recurring, 'expense', today, monthEnd);

    double project(double discretionarySoFar) =>
        daysElapsed > 0 ? (discretionarySoFar / daysElapsed) * daysRemaining : 0.0;

    final projectedIncome =
        incomeSoFar + remainingRecurringIncome + project(incomeDiscretionary);
    final projectedExpenses = expensesSoFar +
        remainingRecurringExpense +
        project(expenseDiscretionary);

    return MonthForecast(
      incomeSoFar: incomeSoFar,
      expensesSoFar: expensesSoFar,
      projectedIncome: projectedIncome,
      projectedExpenses: projectedExpenses,
    );
  }

  static double _remainingRecurringForCategory({
    required List<RecurringTransaction> recurring,
    required int categoryId,
    required DateTime from,
    required DateTime monthEnd,
  }) {
    double sum = 0;
    for (final r in recurring) {
      if (r.type != 'expense' || r.categoryId != categoryId) continue;
      sum += _occurrencesInRange(r, from, monthEnd) * r.amount;
    }
    return sum;
  }

  static double _remainingRecurring(
    List<RecurringTransaction> recurring,
    String type,
    DateTime from,
    DateTime monthEnd,
  ) {
    double sum = 0;
    for (final r in recurring) {
      if (r.type != type) continue;
      sum += _occurrencesInRange(r, from, monthEnd) * r.amount;
    }
    return sum;
  }

  /// Counts occurrences of rule [r] strictly AFTER [from] through [monthEnd]
  /// (inclusive), bounded by the rule's own start/end dates.
  static int _occurrencesInRange(
      RecurringTransaction r, DateTime from, DateTime monthEnd) {
    final start = _dateOnly(r.startDate);
    final hardEnd = r.endDate == null ? monthEnd : _dateOnly(r.endDate!);
    final upper = hardEnd.isBefore(monthEnd) ? hardEnd : monthEnd;

    // First occurrence strictly after `from`.
    var occ = start;
    // Fast-forward to just after `from` without an unbounded loop risk.
    var guard = 0;
    while (!occ.isAfter(from) && guard < 100000) {
      occ = _dateOnly(r.advance(occ));
      guard++;
    }

    var count = 0;
    while (!occ.isAfter(upper) && guard < 100000) {
      if (!occ.isBefore(start)) count++;
      occ = _dateOnly(r.advance(occ));
      guard++;
    }
    return count;
  }

  static DateTime _dateOnly(DateTime d) => DateTime(d.year, d.month, d.day);
}
